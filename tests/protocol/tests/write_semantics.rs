//! Writes only newly generated tables in dedicated test databases.

use sqlx::{AssertSqlSafe, Connection, Executor, MySqlConnection, SqlSafeStr};
use std::{
    env,
    time::{Duration, SystemTime, UNIX_EPOCH},
};

fn table_name() -> String {
    format!(
        "_sqlx_doris_{}_{}",
        std::process::id(),
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos()
    )
}

async fn connect(key: &str) -> MySqlConnection {
    tokio::time::timeout(
        Duration::from_secs(15),
        MySqlConnection::connect(&env::var(key).expect("test URL required")),
    )
    .await
    .unwrap()
    .unwrap()
}

// Dynamic SQL below only inserts identifiers generated by table_name(); values
// always use bind parameters. No user-provided SQL or identifier is interpolated.
async fn ddl(c: &mut MySqlConnection, name: &str, model: &str) {
    let sql = if model == "mysql" {
        format!("CREATE TABLE {name} (id BIGINT PRIMARY KEY, value BIGINT) ENGINE=InnoDB")
    } else {
        format!(
            "CREATE TABLE {name} (id BIGINT NOT NULL, value BIGINT) ENGINE=OLAP {model} \
                KEY(id) DISTRIBUTED BY HASH(id) BUCKETS 1 PROPERTIES ('replication_num'='1', \
                'group_commit_interval_ms'='1000')"
        )
    };
    c.execute(AssertSqlSafe(sql)).await.unwrap();
}

async fn insert(c: &mut MySqlConnection, name: &str, id: i64, value: i64) {
    sqlx::query(AssertSqlSafe(format!(
        "INSERT INTO {name} (id,value) VALUES (?,?)"
    )))
    .bind(id)
    .bind(value)
    .execute(c)
    .await
    .unwrap();
}

async fn count(c: &mut MySqlConnection, name: &str) -> i64 {
    sqlx::query_scalar(AssertSqlSafe(format!("SELECT COUNT(*) FROM {name}")))
        .fetch_one(c)
        .await
        .unwrap()
}

async fn drop_table(c: &mut MySqlConnection, name: &str) {
    c.execute(AssertSqlSafe(format!("DROP TABLE {name}")))
        .await
        .unwrap();
}

#[tokio::test]
#[ignore = "requires both dedicated databases"]
async fn same_parameterized_crud_functions_work_on_mysql_and_doris_unique_tables() {
    for (key, model) in [("MYSQL_TEST_URL", "mysql"), ("DORIS_TEST_URL", "UNIQUE")] {
        let mut c = connect(key).await;
        let table = table_name();
        ddl(&mut c, &table, model).await;
        insert(&mut c, &table, 1, 10).await;
        insert(&mut c, &table, 2, 20).await;
        let actual: i64 = sqlx::query_scalar(AssertSqlSafe(format!(
            "SELECT value FROM {table} WHERE id=?"
        )))
        .bind(1_i64)
        .fetch_one(&mut c)
        .await
        .unwrap();
        assert_eq!(actual, 10);
        sqlx::query(AssertSqlSafe(format!(
            "UPDATE {table} SET value=? WHERE id=?"
        )))
        .bind(30_i64)
        .bind(1_i64)
        .execute(&mut c)
        .await
        .unwrap();
        let actual: i64 = sqlx::query_scalar(AssertSqlSafe(format!(
            "SELECT value FROM {table} WHERE id=?"
        )))
        .bind(1_i64)
        .fetch_one(&mut c)
        .await
        .unwrap();
        assert_eq!(actual, 30);
        sqlx::query(AssertSqlSafe(format!("DELETE FROM {table} WHERE id=?")))
            .bind(2_i64)
            .execute(&mut c)
            .await
            .unwrap();
        assert_eq!(count(&mut c, &table).await, 1);
        drop_table(&mut c, &table).await;
        c.close().await.unwrap();
    }
}

#[tokio::test]
#[ignore = "requires the pinned Doris fixture"]
async fn raw_doris_write_transaction_commit_and_rollback_have_verified_visibility() {
    let mut c = connect("DORIS_TEST_URL").await;
    let table = table_name();
    ddl(&mut c, &table, "DUPLICATE").await;
    c.execute("BEGIN").await.unwrap();
    // Fixed fixture values use COM_QUERY to isolate server transaction semantics
    // from COM_STMT_PREPARE, which has a separate explicit gap test below.
    c.execute(AssertSqlSafe(format!("INSERT INTO {table} VALUES (1,10)")))
        .await
        .unwrap();
    c.execute("COMMIT").await.unwrap();
    assert_eq!(count(&mut c, &table).await, 1);
    c.execute("BEGIN").await.unwrap();
    c.execute(AssertSqlSafe(format!("INSERT INTO {table} VALUES (2,20)")))
        .await
        .unwrap();
    c.execute("ROLLBACK").await.unwrap();
    assert_eq!(count(&mut c, &table).await, 1);
    drop_table(&mut c, &table).await;
    c.close().await.unwrap();
}

#[tokio::test]
#[ignore = "requires the pinned Doris fixture"]
async fn known_gap_preparing_an_insert_after_begin_is_rejected() {
    let mut c = connect("DORIS_TEST_URL").await;
    let table = table_name();
    ddl(&mut c, &table, "DUPLICATE").await;
    c.execute("BEGIN").await.unwrap();
    let error = c
        .prepare(AssertSqlSafe(format!("INSERT INTO {table} VALUES (?,?)")).into_sql_str())
        .await
        .unwrap_err();
    assert!(
        error.to_string().contains("This is in a transaction"),
        "{error}"
    );
    c.execute("ROLLBACK").await.unwrap();
    drop_table(&mut c, &table).await;
    c.close().await.unwrap();
}

#[tokio::test]
#[ignore = "requires the pinned Doris fixture"]
async fn known_gap_an_insert_prepared_before_begin_is_also_rejected_in_the_transaction() {
    let mut c = connect("DORIS_TEST_URL").await;
    let table = table_name();
    ddl(&mut c, &table, "DUPLICATE").await;
    let query = format!("INSERT INTO {table} (id,value) VALUES (?,?)");
    c.prepare(AssertSqlSafe(query.clone()).into_sql_str())
        .await
        .unwrap();
    c.execute("BEGIN").await.unwrap();
    let error = sqlx::query(AssertSqlSafe(query))
        .bind(1_i64)
        .bind(10_i64)
        .execute(&mut c)
        .await
        .unwrap_err();
    assert!(
        error.to_string().contains("This is in a transaction"),
        "{error}"
    );
    c.execute("ROLLBACK").await.unwrap();
    assert_eq!(count(&mut c, &table).await, 0);
    drop_table(&mut c, &table).await;
    c.close().await.unwrap();
}

#[tokio::test]
#[ignore = "requires the pinned Doris fixture"]
async fn duplicate_and_unique_key_tables_have_different_repeated_insert_semantics() {
    let mut c = connect("DORIS_TEST_URL").await;
    for (model, expected) in [("DUPLICATE", 2), ("UNIQUE", 1)] {
        let table = table_name();
        ddl(&mut c, &table, model).await;
        insert(&mut c, &table, 1, 10).await;
        insert(&mut c, &table, 1, 20).await;
        assert_eq!(count(&mut c, &table).await, expected);
        if model == "UNIQUE" {
            let actual: i64 = sqlx::query_scalar(AssertSqlSafe(format!(
                "SELECT value FROM {table} WHERE id=1"
            )))
            .fetch_one(&mut c)
            .await
            .unwrap();
            assert_eq!(actual, 20);
        }
        drop_table(&mut c, &table).await;
    }
    c.close().await.unwrap();
}

#[tokio::test]
#[ignore = "requires the pinned Doris fixture"]
async fn async_group_commit_ack_is_followed_by_bounded_visibility_polling() {
    let mut c = connect("DORIS_TEST_URL").await;
    let table = table_name();
    ddl(&mut c, &table, "DUPLICATE").await;
    c.execute("SET group_commit = async_mode").await.unwrap();
    insert(&mut c, &table, 1, 10).await;
    let first = count(&mut c, &table).await;
    println!("async Group Commit rows visible immediately after ack: {first}");
    let deadline = tokio::time::Instant::now() + Duration::from_secs(20);
    loop {
        if count(&mut c, &table).await == 1 {
            break;
        }
        assert!(
            tokio::time::Instant::now() < deadline,
            "write did not become visible"
        );
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    c.execute("SET group_commit = off_mode").await.unwrap();
    drop_table(&mut c, &table).await;
    c.close().await.unwrap();
}
